BEGIN;

CREATE EXTENSION IF NOT EXISTS citext;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

CREATE TABLE users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supabase_user_id uuid UNIQUE,
  name varchar(255) NOT NULL,
  email citext NOT NULL UNIQUE,
  password varchar(255) NOT NULL,
  branch_id integer,
  role varchar(50) NOT NULL DEFAULT 'customer'
    CHECK (role IN ('customer', 'staff', 'admin')),
  refresh_token varchar(500),
  password_reset_token varchar(500),
  password_reset_expires timestamptz,
  email_verification_token varchar(500),
  email_verified boolean NOT NULL DEFAULT false,
  mfa_secret varchar(500),
  mfa_enabled boolean NOT NULL DEFAULT false,
  failed_login_attempts integer NOT NULL DEFAULT 0
    CHECK (failed_login_attempts >= 0),
  locked_until timestamptz,
  stripe_customer_id varchar(255) UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);

CREATE TABLE brands (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(255) NOT NULL,
  slug citext NOT NULL UNIQUE,
  description text,
  logo_url text,
  website_url text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);

CREATE TABLE collections (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(255) NOT NULL,
  slug citext NOT NULL UNIQUE,
  description text,
  hero_image_url text,
  seo_title varchar(255),
  seo_description varchar(500),
  is_active boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);

CREATE TABLE watches (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_id integer REFERENCES brands(id) ON DELETE SET NULL,
  collection_id integer REFERENCES collections(id) ON DELETE SET NULL,
  brand varchar(255),
  model varchar(255) NOT NULL,
  reference varchar(255),
  sku citext UNIQUE,
  slug citext NOT NULL UNIQUE,
  complication varchar(255),
  case_material varchar(255),
  bracelet_material varchar(255),
  dial varchar(255),
  hour_markings varchar(255),
  lunette_material varchar(255),
  sale_price numeric(12,2) NOT NULL CHECK (sale_price >= 0),
  msrp numeric(12,2) CHECK (msrp IS NULL OR msrp >= 0),
  stock_status varchar(50) NOT NULL DEFAULT 'in_stock'
    CHECK (stock_status IN ('in_stock', 'low_stock', 'out_of_stock', 'discontinued')),
  stock_quantity integer NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
  movement varchar(255),
  condition varchar(50) NOT NULL DEFAULT 'new'
    CHECK (condition IN ('new', 'pre_owned', 'vintage')),
  case_size numeric(5,2) CHECK (case_size IS NULL OR case_size > 0),
  water_resistance varchar(50),
  power_reserve varchar(50),
  description text,
  short_description varchar(500),
  is_active boolean NOT NULL DEFAULT true,
  is_featured boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);

CREATE TABLE assets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  watch_id integer NOT NULL REFERENCES watches(id) ON DELETE CASCADE,
  url text NOT NULL,
  type varchar(50) NOT NULL DEFAULT 'image'
    CHECK (type IN ('image', 'thumbnail', 'video', 'document')),
  alt_text varchar(500),
  sort_order integer NOT NULL DEFAULT 0,
  width integer CHECK (width IS NULL OR width > 0),
  height integer CHECK (height IS NULL OR height > 0),
  file_size integer CHECK (file_size IS NULL OR file_size >= 0),
  mime_type varchar(100),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE inventory_adjustments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  watch_id integer NOT NULL REFERENCES watches(id) ON DELETE CASCADE,
  adjustment_type varchar(50) NOT NULL
    CHECK (adjustment_type IN ('sale', 'return', 'damage', 'restock', 'adjustment')),
  quantity_change integer NOT NULL CHECK (quantity_change <> 0),
  previous_quantity integer NOT NULL CHECK (previous_quantity >= 0),
  new_quantity integer NOT NULL CHECK (new_quantity >= 0),
  reason text,
  reference_id integer,
  reference_type varchar(50),
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE carts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer REFERENCES users(id) ON DELETE CASCADE,
  guest_token varchar(255),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT carts_owner_check CHECK (
    (user_id IS NOT NULL AND guest_token IS NULL) OR
    (user_id IS NULL AND guest_token IS NOT NULL)
  )
);

CREATE TABLE cart_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cart_id integer NOT NULL REFERENCES carts(id) ON DELETE CASCADE,
  watch_id integer NOT NULL REFERENCES watches(id) ON DELETE CASCADE,
  quantity integer NOT NULL DEFAULT 1 CHECK (quantity > 0),
  price_at_added numeric(12,2) NOT NULL CHECK (price_at_added >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (cart_id, watch_id)
);

CREATE TABLE wishlists (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  watch_id integer NOT NULL REFERENCES watches(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, watch_id)
);

CREATE TABLE orders (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number varchar(50) NOT NULL UNIQUE,
  user_id integer REFERENCES users(id) ON DELETE SET NULL,
  guest_email citext,
  status varchar(50) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'confirmed', 'processing', 'shipped', 'delivered', 'cancelled', 'refunded')),
  subtotal numeric(12,2) NOT NULL CHECK (subtotal >= 0),
  tax_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
  shipping_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (shipping_amount >= 0),
  total_amount numeric(12,2) NOT NULL CHECK (total_amount >= 0),
  currency char(3) NOT NULL DEFAULT 'USD',
  shipping_address jsonb NOT NULL,
  billing_address jsonb,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT orders_total_check CHECK (total_amount = subtotal + tax_amount + shipping_amount)
);

CREATE TABLE order_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  watch_id integer NOT NULL REFERENCES watches(id) ON DELETE RESTRICT,
  quantity integer NOT NULL CHECK (quantity > 0),
  unit_price numeric(12,2) NOT NULL CHECK (unit_price >= 0),
  total_price numeric(12,2) NOT NULL CHECK (total_price >= 0),
  watch_snapshot jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT order_items_total_check CHECK (total_price = unit_price * quantity)
);

CREATE TABLE payments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  payment_intent_id varchar(255) UNIQUE,
  payment_method varchar(50) NOT NULL,
  amount numeric(12,2) NOT NULL CHECK (amount >= 0),
  currency char(3) NOT NULL DEFAULT 'USD',
  status varchar(50) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'requires_action', 'processing', 'succeeded', 'failed', 'cancelled', 'refunded')),
  transaction_id varchar(255),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE shipments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  tracking_number varchar(255) UNIQUE,
  carrier varchar(100),
  status varchar(50) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'label_created', 'in_transit', 'delivered', 'exception', 'returned')),
  shipped_at timestamptz,
  delivered_at timestamptz,
  estimated_delivery timestamptz,
  shipping_address jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE order_status_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  status varchar(50) NOT NULL,
  previous_status varchar(50),
  notes text,
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE recently_viewed (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer REFERENCES users(id) ON DELETE CASCADE,
  guest_token varchar(255),
  watch_id integer NOT NULL REFERENCES watches(id) ON DELETE CASCADE,
  viewed_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT recently_viewed_owner_check CHECK (
    (user_id IS NOT NULL AND guest_token IS NULL) OR
    (user_id IS NULL AND guest_token IS NOT NULL)
  )
);

CREATE TABLE addresses (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type varchar(20) NOT NULL DEFAULT 'shipping'
    CHECK (type IN ('shipping', 'billing', 'both')),
  label varchar(100),
  name varchar(255) NOT NULL,
  street varchar(255) NOT NULL,
  street2 varchar(255),
  city varchar(100) NOT NULL,
  state varchar(100) NOT NULL,
  zip varchar(20) NOT NULL,
  country char(2) NOT NULL DEFAULT 'US',
  phone varchar(30),
  is_default boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE payment_methods (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type varchar(50) NOT NULL,
  provider varchar(50),
  provider_payment_method_id varchar(255) UNIQUE,
  last4 char(4),
  brand varchar(50),
  expiry_month smallint CHECK (expiry_month BETWEEN 1 AND 12),
  expiry_year smallint CHECK (expiry_year IS NULL OR expiry_year >= 2020),
  is_default boolean NOT NULL DEFAULT false,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Catalog browsing, filtering, sorting, and detail lookups.
CREATE INDEX watches_catalog_created_idx
  ON watches (created_at DESC) WHERE deleted_at IS NULL AND is_active;
CREATE INDEX watches_catalog_price_idx
  ON watches (sale_price, id) WHERE deleted_at IS NULL AND is_active;
CREATE INDEX watches_brand_catalog_idx
  ON watches (brand_id, created_at DESC) WHERE deleted_at IS NULL AND is_active;
CREATE INDEX watches_collection_catalog_idx
  ON watches (collection_id, created_at DESC) WHERE deleted_at IS NULL AND is_active;
CREATE INDEX watches_featured_idx
  ON watches (updated_at DESC) WHERE deleted_at IS NULL AND is_active AND is_featured;
CREATE INDEX watches_stock_idx
  ON watches (stock_status, stock_quantity) WHERE deleted_at IS NULL AND is_active;
CREATE INDEX watches_search_idx ON watches USING gin (
  to_tsvector('english',
    coalesce(brand, '') || ' ' || coalesce(model, '') || ' ' ||
    coalesce(reference, '') || ' ' || coalesce(complication, '') || ' ' ||
    coalesce(description, ''))
);
CREATE INDEX watches_brand_trgm_idx ON watches USING gin (brand gin_trgm_ops);
CREATE INDEX watches_model_trgm_idx ON watches USING gin (model gin_trgm_ops);
CREATE INDEX watches_reference_trgm_idx ON watches USING gin (reference gin_trgm_ops);
CREATE INDEX assets_watch_display_idx ON assets (watch_id, sort_order, created_at);

-- Cart and wishlist hot paths.
CREATE UNIQUE INDEX carts_user_unique_idx ON carts (user_id) WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX carts_guest_unique_idx ON carts (guest_token) WHERE guest_token IS NOT NULL;
CREATE INDEX cart_items_cart_created_idx ON cart_items (cart_id, created_at);
CREATE INDEX cart_items_watch_idx ON cart_items (watch_id);
CREATE INDEX wishlists_user_created_idx ON wishlists (user_id, created_at DESC);

-- Checkout, order history, payment webhooks, and fulfillment.
CREATE INDEX orders_user_created_idx ON orders (user_id, created_at DESC);
CREATE INDEX orders_user_status_created_idx ON orders (user_id, status, created_at DESC);
CREATE INDEX orders_status_created_idx ON orders (status, created_at DESC);
CREATE INDEX orders_guest_email_created_idx ON orders (guest_email, created_at DESC)
  WHERE guest_email IS NOT NULL;
CREATE INDEX order_items_order_created_idx ON order_items (order_id, created_at);
CREATE INDEX order_items_watch_idx ON order_items (watch_id);
CREATE INDEX payments_order_created_idx ON payments (order_id, created_at);
CREATE INDEX payments_status_created_idx ON payments (status, created_at DESC);
CREATE INDEX shipments_order_created_idx ON shipments (order_id, created_at);
CREATE INDEX shipments_status_idx ON shipments (status) WHERE status <> 'delivered';
CREATE INDEX order_status_events_order_created_idx
  ON order_status_events (order_id, created_at);

-- Account and behavioral history.
CREATE INDEX addresses_user_sort_idx ON addresses (user_id, is_default DESC, created_at DESC);
CREATE UNIQUE INDEX addresses_one_default_per_type_idx
  ON addresses (user_id, type) WHERE is_default;
CREATE INDEX payment_methods_user_sort_idx
  ON payment_methods (user_id, is_default DESC, created_at DESC);
CREATE UNIQUE INDEX payment_methods_one_default_idx
  ON payment_methods (user_id) WHERE is_default;
CREATE INDEX recently_viewed_user_idx
  ON recently_viewed (user_id, watch_id, viewed_at DESC) WHERE user_id IS NOT NULL;
CREATE INDEX recently_viewed_guest_idx
  ON recently_viewed (guest_token, watch_id, viewed_at DESC) WHERE guest_token IS NOT NULL;
CREATE INDEX inventory_adjustments_watch_created_idx
  ON inventory_adjustments (watch_id, created_at DESC);

CREATE TRIGGER users_set_updated_at BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER brands_set_updated_at BEFORE UPDATE ON brands
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER collections_set_updated_at BEFORE UPDATE ON collections
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER watches_set_updated_at BEFORE UPDATE ON watches
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER assets_set_updated_at BEFORE UPDATE ON assets
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER carts_set_updated_at BEFORE UPDATE ON carts
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER cart_items_set_updated_at BEFORE UPDATE ON cart_items
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER orders_set_updated_at BEFORE UPDATE ON orders
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER payments_set_updated_at BEFORE UPDATE ON payments
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER shipments_set_updated_at BEFORE UPDATE ON shipments
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER addresses_set_updated_at BEFORE UPDATE ON addresses
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER payment_methods_set_updated_at BEFORE UPDATE ON payment_methods
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- The Express API owns application data access. Supabase Auth is exposed to
-- the browser, so every Data API table must deny direct access by default.
DO $$
DECLARE
  table_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'users', 'brands', 'collections', 'watches', 'assets',
    'inventory_adjustments', 'carts', 'cart_items', 'wishlists',
    'orders', 'order_items', 'payments', 'shipments',
    'order_status_events', 'recently_viewed', 'addresses', 'payment_methods'
  ]
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
  END LOOP;
END;
$$;

COMMIT;
